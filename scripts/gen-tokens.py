#!/usr/bin/env python3
"""Generate the app's Tokens.kt and Glyphs.kt from the design files (ported from trismegistus-mac's generator).

  python3 scripts/gen-tokens.py [out-dir]

Reads design/tokens.json (the Mac app's tokens), design/endfield-palette.json (what {endfield.<name>} names),
design/android-tokens.json (the phone's type roles in sp and sizes in dp) and design/icons.json (16-unit stroke icons).
The output defaults to app/src/main/kotlin/dev/xmuramasa/trismegistus/ui/theme. An unknown reference fails.
"""
import json, pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
design = root / "design"
if len(sys.argv) > 2:
    sys.exit(f"usage: {sys.argv[0]} [out-dir]")
dest = pathlib.Path(sys.argv[1]) if len(sys.argv) == 2 else root / "app/src/main/kotlin/dev/xmuramasa/trismegistus/ui/theme"
fonts = root / "app/src/main/res/font"
endfield = json.load(open(design / "endfield-palette.json"))["colors"]
tokens = json.load(open(design / "tokens.json"))
phone = json.load(open(design / "android-tokens.json"))
icons = json.load(open(design / "icons.json"))["icons"]
KEYWORDS = {"as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is",
            "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "val", "var",
            "when", "while", "default"}


def camel(name):
    head, *rest = name.split("-")
    c = head + "".join(w[:1].upper() + w[1:] for w in rest)
    return f"`{c}`" if c in KEYWORDS else c


def pascal(name):
    c = camel(name).strip("`")
    return c[:1].upper() + c[1:]


def num(v):
    """A number as Kotlin writes it: 12, 1.5, 0.55."""
    return str(int(v)) if float(v).is_integer() else repr(round(float(v), 4))


def flt(v):
    return f"{num(v)}f"


def hex_of(ref):
    """A #rrggbb, {endfield.x} or {color.palette.x} value as RRGGBB."""
    m = re.fullmatch(r"\{(endfield|color\.palette)\.([\w-]+)\}", ref)
    if not m:
        if not re.fullmatch(r"#[0-9A-Fa-f]{6}", ref):
            sys.exit(f"not a colour or reference: {ref}")
        return ref[1:].upper()
    group, name = m.groups()
    if group == "endfield":
        if name not in endfield or name.startswith("_"):
            sys.exit(f"unknown reference {ref}")
        return endfield[name]["hex"][1:].upper()
    if name not in tokens["color"]["palette"]:
        sys.exit(f"unknown reference {ref}")
    return hex_of(tokens["color"]["palette"][name]["$value"])


def palette_ref(ref):
    """{color.palette.x} as `Palette.x`: roles point at the palette so the two stay one."""
    m = re.fullmatch(r"\{color\.palette\.([\w-]+)\}", ref)
    if not m or m.group(1) not in tokens["color"]["palette"]:
        sys.exit(f"unknown reference {ref}")
    return f"Palette.{camel(m.group(1))}"


def leaves(group):
    return [(k, v) for k, v in group.items() if not k.startswith("$")]


def doc(token, indent):
    d = token.get("$description") if isinstance(token, dict) else None
    return [f"{indent}/** {d} */"] if d else []


HEADER = "// Generated by scripts/gen-tokens.py from design/{}. Do not edit."

out = [
    HEADER.format("tokens.json, endfield-palette.json and android-tokens.json"),
    "",
    "package dev.xmuramasa.trismegistus.ui.theme",
    "",
    "import androidx.compose.ui.graphics.Color",
    "import androidx.compose.ui.text.TextStyle",
    "import androidx.compose.ui.text.font.Font",
    "import androidx.compose.ui.text.font.FontFamily",
    "import androidx.compose.ui.text.font.FontWeight",
    "import androidx.compose.ui.unit.Dp",
    "import androidx.compose.ui.unit.dp",
    "import androidx.compose.ui.unit.sp",
    "import dev.xmuramasa.trismegistus.R",
    "",
    "/** `color.palette`: the Endfield colours and ours (light mode only). Views use the roles in [Ink] where one fits. */",
    "public object Palette {",
]
for name, t in leaves(tokens["color"]["palette"]):
    out += doc(t, "    ") + [f"    public val {camel(name)}: Color = Color(0xFF{hex_of(t['$value'])})"]
out += ["}", ""]


def role_value(v):
    if isinstance(v, dict):  # {"color": ref, "opacity": "{opacity.x}"}: a colour at an opacity token
        m = re.fullmatch(r"\{opacity\.([\w-]+)\}", v["opacity"])
        if not m or m.group(1) not in tokens["opacity"]:
            sys.exit(f"unknown reference {v['opacity']}")
        return "Color", f"{palette_ref(v['color'])}.copy(alpha = Opacity.{camel(m.group(1))})"
    if isinstance(v, list):
        return "List<Color>", f"listOf({', '.join(palette_ref(r) for r in v)})"
    return "Color", palette_ref(v)


out += ["/** `color.role`: colours by job. */", "public object Ink {"]
for name, t in leaves(tokens["color"]["role"]):
    if "$value" in t:
        kind, value = role_value(t["$value"])
        out += doc(t, "    ") + [f"    public val {camel(name)}: {kind} = {value}"]
    else:
        out += [f"    public object {pascal(name)} {{"]
        for k, sub in leaves(t):
            kind, value = role_value(sub["$value"])
            out += doc(sub, "        ") + [f"        public val {camel(k)}: {kind} = {value}"]
        out += ["    }"]
out += ["}", ""]


def scalars(group, kt_name, kind, summary, fmt):
    lines = [f"/** {summary} */", f"public object {kt_name} {{"]
    for name, t in leaves(group):
        v = t["$value"] if isinstance(t, dict) else t
        if not isinstance(v, (int, float)):
            sys.exit(f"{kt_name}.{name}: not a number")
        lines += doc(t, "    ") + [f"    public val {camel(name)}: {kind} = {fmt(v)}"]
    return lines + ["}", ""]


out += scalars(tokens["opacity"], "Opacity", "Float", "`opacity`.", flt)
out += scalars(tokens["space"], "Space", "Dp", "`space`: the strict spacing scale; literals round up to the next step.",
               lambda v: f"{num(v)}.dp")
out += scalars(tokens["radius"], "Radius", "Dp", "`radius`: Endfield is square.", lambda v: f"{num(v)}.dp")
out += scalars(tokens["stroke"], "Strokes", "Dp", "`stroke`: line widths and bars.", lambda v: f"{num(v)}.dp")
out += scalars(phone["size"], "Sizes", "Dp", "The phone's component sizes (android-tokens.json `size`).",
               lambda v: f"{num(v)}.dp")
out += scalars({k.replace("padding-", ""): v for k, v in phone["row"].items()}, "RowPadding", "Dp",
               "A list row's padding and gap (android-tokens.json `row`).", lambda v: f"{num(v)}.dp")

steel, stops = phone["gradient"]["steel"], phone["gradient"]["steel-stops"]
if len(steel) != len(stops):
    sys.exit("gradient.steel and steel-stops differ in length")
out += [
    "/** The steel top bar's gradient, left to right. */",
    "public object Gradient {",
    f"    public val steel: List<Color> = listOf({', '.join(palette_ref(c) for c in steel)})",
    f"    public val steelStops: List<Float> = listOf({', '.join(flt(s) for s in stops)})",
    "}",
    "",
]

# Fonts: each family's faces are the bundled res/font/<family>_<weight>.ttf.
weights = {400: "regular", 500: "medium", 600: "semi_bold", 700: "bold"}
families = sorted({t["family"] for t in phone["type"].values()})
out += ["/** The bundled families (res/font, SIL OFL 1.1). */", "public object Fonts {"]
for fam in families:
    stem = fam.replace("-", "_")
    faces = []
    for w, wname in weights.items():
        f = fonts / f"{stem}_{wname}.ttf"
        if not f.exists():
            sys.exit(f"missing font file {f}")
        faces.append(f"Font(R.font.{stem}_{wname}, FontWeight.W{w})")
    out += [f"    public val {camel(fam)}: FontFamily = FontFamily({', '.join(faces)})"]
out += ["}", ""]

out += [
    "/** A type role: its style, and whether its text is set in capitals. */",
    "public class TypeRole(public val style: TextStyle, public val caps: Boolean)",
    "",
    "/** The phone's type roles (android-tokens.json `type`), sizes in sp. */",
    "public object Type {",
]
for name, v in phone["type"].items():
    if v["family"] not in families or v["weight"] not in weights:
        sys.exit(f"type.{name}: unknown family or weight")
    style = (f"TextStyle(fontFamily = Fonts.{camel(v['family'])}, fontWeight = FontWeight.W{v['weight']}, "
             f"fontSize = {num(v['size'])}.sp, lineHeight = {num(v['size'] * v['lineHeight'])}.sp, "
             f"letterSpacing = {num(v['letterSpacing'])}.sp)")
    out += [f"    public val {camel(name)}: TypeRole = TypeRole({style}, caps = {'true' if v['caps'] else 'false'})"]
out += ["}", ""]

dest.mkdir(parents=True, exist_ok=True)
(dest / "Tokens.kt").write_text("\n".join(out))


# Icons: SVG paths and circles (a circle becomes two arcs) on a 16-unit viewBox, stroked 1.5 with square caps.
def circle(a):
    cx, cy, r = (float(a[k]) for k in ("cx", "cy", "r"))
    return f"M{num(cx - r)} {num(cy)}a{num(r)} {num(r)} 0 1 0 {num(2 * r)} 0a{num(r)} {num(r)} 0 1 0 {num(-2 * r)} 0"


glyphs = [
    HEADER.format("icons.json"),
    "",
    "package dev.xmuramasa.trismegistus.ui.theme",
    "",
    "import androidx.compose.ui.graphics.Color",
    "import androidx.compose.ui.graphics.SolidColor",
    "import androidx.compose.ui.graphics.StrokeCap",
    "import androidx.compose.ui.graphics.StrokeJoin",
    "import androidx.compose.ui.graphics.vector.ImageVector",
    "import androidx.compose.ui.graphics.vector.addPathNodes",
    "import androidx.compose.ui.unit.dp",
    "",
    "/** The draft's icons (16-unit viewBox, 1.5 stroke, square caps). `Icon` tints them with the content colour. */",
    "public object Glyphs {",
]
for name, svg in icons.items():
    parts = []
    for tag, attrs in re.findall(r"<(path|circle)\s([^>]*?)/?>", svg):
        a = dict(re.findall(r'([\w-]+)="([^"]*)"', attrs))
        d = a["d"] if tag == "path" else circle(a)
        parts.append(f'"{d}" to {"true" if a.get("fill") == "currentColor" else "false"}')
    if not parts:
        sys.exit(f"icon {name}: no shapes")
    glyphs += [f"    public val {camel(name)}: ImageVector by lazy {{ glyph({', '.join(parts)}) }}"]
glyphs += [
    "}",
    "",
    "/** Each part is SVG path data and whether it is filled (else stroked). */",
    "private fun glyph(vararg parts: Pair<String, Boolean>): ImageVector =",
    "    ImageVector.Builder(defaultWidth = 16.dp, defaultHeight = 16.dp, viewportWidth = 16f, viewportHeight = 16f).apply {",
    "        for ((d, filled) in parts) {",
    "            addPath(",
    "                addPathNodes(d),",
    "                fill = if (filled) SolidColor(Color.Black) else null,",
    "                stroke = if (filled) null else SolidColor(Color.Black),",
    "                strokeLineWidth = 1.5f,",
    "                strokeLineCap = StrokeCap.Square,",
    "                strokeLineJoin = StrokeJoin.Miter,",
    "            )",
    "        }",
    "    }.build()",
    "",
]
(dest / "Glyphs.kt").write_text("\n".join(glyphs))
print(f"wrote {dest / 'Tokens.kt'} and {dest / 'Glyphs.kt'}")
